import os
import uuid
from datetime import datetime, timezone
from pathlib import Path
from typing import Dict, Any, List

from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable
)
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from backend.config import settings

RISK_COLORS = {
    "LOW": colors.HexColor("#2e7d32"),       # Forest Green
    "MEDIUM": colors.HexColor("#f57c00"),    # Amber Orange
    "HIGH": colors.HexColor("#c62828"),      # Strong Red
    "CRITICAL": colors.HexColor("#880e4f")   # Deep Burgundy Red
}

class PDFReportGenerator:
    @classmethod
    def generate_report(cls, analysis_data: Dict[str, Any]) -> str:
        """
        Generate a comprehensive PDF audit report and return the saved path.
        """
        filename = f"privacy_audit_{uuid.uuid4().hex[:10]}.pdf"
        filepath = settings.REPORT_OUTPUT_DIR / filename
        
        doc = SimpleDocTemplate(
            str(filepath),
            pagesize=letter,
            rightMargin=36,
            leftMargin=36,
            topMargin=36,
            bottomMargin=36
        )
        
        styles = getSampleStyleSheet()
        
        # Custom Typography Styles
        title_style = ParagraphStyle(
            "ReportTitle",
            parent=styles["Heading1"],
            fontSize=20,
            leading=24,
            textColor=colors.HexColor("#1a237e"),
            spaceAfter=6
        )
        
        h2_style = ParagraphStyle(
            "ReportH2",
            parent=styles["Heading2"],
            fontSize=13,
            leading=17,
            textColor=colors.HexColor("#0d47a1"),
            spaceBefore=12,
            spaceAfter=6
        )
        
        body_style = ParagraphStyle(
            "ReportBody",
            parent=styles["Normal"],
            fontSize=9,
            leading=12,
            textColor=colors.HexColor("#212121")
        )
        
        bold_body = ParagraphStyle(
            "ReportBoldBody",
            parent=body_style,
            fontName="Helvetica-Bold"
        )
        
        code_style = ParagraphStyle(
            "ReportCode",
            parent=body_style,
            fontName="Courier",
            fontSize=8,
            leading=10,
            textColor=colors.HexColor("#b71c1c")
        )

        story = []

        # Header Title & Subtitle
        story.append(Paragraph("EXPLAINABLE PRIVACY & PERMISSION AUDIT REPORT", title_style))
        story.append(Paragraph(
            f"Generated by Antigravity Cybersecurity Analyzer (PS02) | {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M:%S UTC')}",
            body_style
        ))
        story.append(Spacer(1, 10))
        story.append(HRFlowable(width="100%", thickness=2, color=colors.HexColor("#1a237e"), spaceAfter=12))

        # Executive Summary & Risk Gauge Banner
        risk_level = analysis_data.get("risk_level", "LOW")
        risk_score = analysis_data.get("risk_score", 0.0)
        banner_color = RISK_COLORS.get(risk_level, colors.HexColor("#333333"))

        gauge_data = [
            [
                Paragraph("<b>Application:</b> " + str(analysis_data.get("app_name")), body_style),
                Paragraph(f"<b>RISK ASSESSMENT:</b> <font color='white'><b>{risk_level} ({risk_score}/100)</b></font>", bold_body)
            ],
            [
                Paragraph("<b>Package ID:</b> " + str(analysis_data.get("package_name")), body_style),
                Paragraph(f"<b>Dangerous Permissions:</b> {analysis_data.get('dangerous_count', 0)} of {analysis_data.get('total_permissions', 0)}", body_style)
            ]
        ]
        
        gauge_table = Table(gauge_data, colWidths=[300, 240])
        gauge_table.setStyle(TableStyle([
            ('BACKGROUND', (1, 0), (1, 0), banner_color),
            ('TEXTCOLOR', (1, 0), (1, 0), colors.white),
            ('ALIGN', (0, 0), (-1, -1), 'LEFT'),
            ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
            ('TOPPADDING', (0, 0), (-1, -1), 6),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
            ('LEFTPADDING', (0, 0), (-1, -1), 8),
            ('RIGHTPADDING', (0, 0), (-1, -1), 8),
            ('BOX', (0, 0), (-1, -1), 1, colors.HexColor("#e0e0e0")),
            ('INNERGRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#eeeeee")),
        ]))
        story.append(gauge_table)
        story.append(Spacer(1, 12))

        # Application Metadata & Security Posture
        story.append(Paragraph("1. Application Manifest Security Posture", h2_style))
        meta_table_data = [
            [
                Paragraph("<b>Target SDK</b>", body_style),
                Paragraph(str(analysis_data.get("target_sdk")), body_style),
                Paragraph("<b>Min SDK</b>", body_style),
                Paragraph(str(analysis_data.get("min_sdk")), body_style)
            ],
            [
                Paragraph("<b>Exported Components</b>", body_style),
                Paragraph(str(analysis_data.get("exported_components_count")), body_style),
                Paragraph("<b>Version Name / Code</b>", body_style),
                Paragraph(f"{analysis_data.get('version_name')} (v{analysis_data.get('version_code')})", body_style)
            ]
        ]
        meta_table = Table(meta_table_data, colWidths=[135, 135, 135, 135])
        meta_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor("#f8f9fa")),
            ('BOX', (0, 0), (-1, -1), 0.5, colors.HexColor("#cccccc")),
            ('INNERGRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#e0e0e0")),
            ('TOPPADDING', (0, 0), (-1, -1), 4),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
        ]))
        story.append(meta_table)

        # Target SDK warnings if any
        sdk_warnings = analysis_data.get("target_sdk_warnings", [])
        if sdk_warnings:
            story.append(Spacer(1, 6))
            for warn in sdk_warnings:
                story.append(Paragraph(f"• <font color='#c62828'><b>WARNING:</b></font> {warn}", body_style))

        # Multi-Permission Dangerous Combinations
        combos: List[Dict[str, Any]] = analysis_data.get("combo_findings", [])
        story.append(Spacer(1, 8))
        story.append(Paragraph(f"2. Multi-Permission Threat Chains ({len(combos)} Detected)", h2_style))
        if combos:
            combo_rows = [[
                Paragraph("<b>Attack Chain</b>", bold_body),
                Paragraph("<b>Severity</b>", bold_body),
                Paragraph("<b>Explainable Threat Scenario</b>", bold_body)
            ]]
            for c in combos:
                combo_rows.append([
                    Paragraph(f"<b>{c.get('name')}</b><br/><font color='#616161'>Required: {', '.join(c.get('matched_permissions', []))}</font>", body_style),
                    Paragraph(f"<font color='#b71c1c'><b>{c.get('severity')}</b></font>", bold_body),
                    Paragraph(c.get("explanation", ""), body_style)
                ])
            combo_table = Table(combo_rows, colWidths=[160, 70, 310])
            combo_table.setStyle(TableStyle([
                ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor("#ffebee")),
                ('BOX', (0, 0), (-1, -1), 0.5, colors.HexColor("#ef9a9a")),
                ('INNERGRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#ffcdd2")),
                ('TOPPADDING', (0, 0), (-1, -1), 5),
                ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
                ('VALIGN', (0, 0), (-1, -1), 'TOP')
            ]))
            story.append(combo_table)
        else:
            story.append(Paragraph("✓ No high-risk multi-permission correlation chains (e.g. stalkerware/surveillance patterns) were triggered.", body_style))

        # Privacy Policy Discrepancy Findings
        discrepancies: List[Dict[str, Any]] = analysis_data.get("discrepancies", [])
        story.append(Spacer(1, 8))
        story.append(Paragraph(f"3. Privacy Policy & Disclosure Discrepancies ({len(discrepancies)} Detected)", h2_style))
        if discrepancies:
            disc_rows = [[
                Paragraph("<b>Permission / Domain</b>", bold_body),
                Paragraph("<b>Discrepancy Type</b>", bold_body),
                Paragraph("<b>Explanation & Remediation</b>", bold_body)
            ]]
            for d in discrepancies:
                disc_rows.append([
                    Paragraph(f"<font name='Courier'>{d.get('permission_name')}</font>", code_style),
                    Paragraph(f"<b>{d.get('issue_type')}</b><br/><font color='#c62828'>{d.get('severity')}</font>", body_style),
                    Paragraph(f"{d.get('explanation')}<br/><br/><b>Fix:</b> {d.get('remediation')}", body_style)
                ])
            disc_table = Table(disc_rows, colWidths=[150, 110, 280])
            disc_table.setStyle(TableStyle([
                ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor("#fff3e0")),
                ('BOX', (0, 0), (-1, -1), 0.5, colors.HexColor("#ffe0b2")),
                ('INNERGRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#ffe0b2")),
                ('TOPPADDING', (0, 0), (-1, -1), 5),
                ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
                ('VALIGN', (0, 0), (-1, -1), 'TOP')
            ]))
            story.append(disc_table)
        else:
            story.append(Paragraph("✓ All declared permissions align transparently with policy disclosures.", body_style))

        # Permission Details Matrix
        perms: List[Dict[str, Any]] = analysis_data.get("permissions", [])
        story.append(Spacer(1, 8))
        story.append(Paragraph(f"4. Permission Explainability & Risk Matrix ({len(perms)} Total)", h2_style))
        
        perm_rows = [[
            Paragraph("<b>Permission</b>", bold_body),
            Paragraph("<b>Group / Level</b>", bold_body),
            Paragraph("<b>Privacy Impact & Remediation</b>", bold_body)
        ]]

        for p in perms[:15]:  # List top 15 prioritized permissions in PDF to prevent page blowout
            prot_color = "#b71c1c" if p.get("protection_level") in ("dangerous", "special") else "#2e7d32"
            perm_rows.append([
                Paragraph(f"<b>{p.get('short_name')}</b><br/><font name='Courier' size='7'>{p.get('name')}</font>", body_style),
                Paragraph(f"{p.get('group')}<br/><font color='{prot_color}'><b>{p.get('protection_level')}</b></font><br/>Score: {p.get('severity_score')}/10", body_style),
                Paragraph(
                    f"<b>Risk:</b> {p.get('privacy_risk')}<br/>"
                    f"<b>Remediation:</b> {p.get('remediation')}",
                    body_style
                )
            ])
            
        perm_table = Table(perm_rows, colWidths=[130, 90, 320])
        perm_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor("#e8eaf6")),
            ('BOX', (0, 0), (-1, -1), 0.5, colors.HexColor("#c5cae9")),
            ('INNERGRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#e8eaf6")),
            ('TOPPADDING', (0, 0), (-1, -1), 4),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
            ('VALIGN', (0, 0), (-1, -1), 'TOP')
        ]))
        story.append(perm_table)

        # Build document
        doc.build(story)
        return str(filepath)
